function addfunction(parameter1, parameter2) {
  // code to be executed
  return parameter1 + parameter2; // Optional: returns a value
}

function subtractfunction(parameter1, parameter2) {
  // code to be executed
  return parameter1 - parameter2; // Optional: returns a value
}

// Calling the function
let result = addfunction(5, 10); 
console.log(result); // Output: 15

let subtractionResult = subtractfunction(10, 5);
console.log(subtractionResult); // Output: 5